def render_benchmark(facts: Facts) -> str:
    bench = _benchmark_cached()
    if bench is None:
        return "The benchmark needs a source checkout with the dev extra installed."
    harness, results = bench
    total = harness.totals(results)
    ratchet = harness.load_ratchet()
    rows = []
    for result in results:
        rows.append(
            [
                f"`{result.fixture}`",
                f"{len(result.found)}/{result.total}",
                f"{result.recall:.0%}",
                len(result.violations),
                result.finding_count,
            ]
        )
    rows.append(
        [
            "**Total**",
            f"**{total.found}/{total.total}**",
            f"**{total.recall:.0%}**",
            f"**{total.violations}**",
            sum(r.finding_count for r in results),
        ]
    )
    out = [
        f"On this build ThreatCode finds **{total.found} of the {total.total}** planted issues"
        f" ({total.recall:.0%}) and reports **{total.violations}** findings on resources that"
        f" are listed as hardened.",
        "",
        table(["Fixture", "Found", "Recall", "Violations", "Findings"], rows),
    ]
    known = [(r.fixture, e) for r in results for e in r.missed if e.known_miss]
    unexplained = [(r.fixture, e) for r in results for e in r.unexplained_misses]
    if known or unexplained:
        out += ["", "### Issues the build does not find", ""]
        for fixture, entry in known + unexplained:
            reason = " ".join((entry.known_miss or "no explanation recorded").split())
            out.append(f"- `{fixture}`, `{entry.resource}`: {' '.join(entry.why.split())}")
            out.append(f"  {reason}")
    if ratchet is not None:
        out += [
            "",
            f"The ratchet in `tests/test_quality/expected/ratchet.yml` is a recall of at least"
            f" {ratchet.min_recall:.2%} with at most {ratchet.max_violations} violations and"
            f" {ratchet.max_companion_duplicates} companion duplicates.",
        ]
    return "\n".join(out)


