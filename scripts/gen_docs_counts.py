def region_pattern(name: str) -> re.Pattern[str]:
    tag = re.escape(name)
    return re.compile(
        rf"(?P<open><!-- gen:{tag} -->)\n(?P<body>.*?)\n?(?P<close><!-- /gen:{tag} -->)",
        re.DOTALL,
    )


def replace_region(text: str, name: str, body: str) -> str | None:
    """The page with region ``name`` replaced, or ``None`` when the page has no such region."""
    pattern = region_pattern(name)
    if not pattern.search(text):
        return None
    return pattern.sub(
        lambda m: f"{m.group('open')}\n{body.strip()}\n{m.group('close')}", text, count=1
    )


def replace_counts(text: str, counts: dict[str, Any]) -> tuple[str, list[str]]:
    """Rewrite every ``<number><!-- count:name -->``; returns the text and unknown names."""
    unknown: list[str] = []

    def sub(match: re.Match[str]) -> str:
        name = match.group("name")
        if name not in counts:
            unknown.append(name)
            return match.group(0)
        value = counts[name]
        shown = f"{value:,}" if isinstance(value, int) and value >= 10_000 else str(value)
        return f"{shown}<!-- count:{name} -->"

    return COUNT_RE.sub(sub, text), unknown


def documentation_files() -> list[Path]:
    files = [REPO_ROOT / "README.md", REPO_ROOT / "SECURITY.md"]
    files += sorted((REPO_ROOT / "docs").glob("*.md"))
    files += sorted((REPO_ROOT / "examples").rglob("README.md"))
    return [f for f in files if f.is_file()]


def compute(facts: Facts) -> dict[Path, str]:
    """The desired content of every generated page and every page with a region or a count."""
    desired: dict[Path, str] = {}
    problems: list[str] = []
    for relative, render in FULL_PAGES.items():
        desired[REPO_ROOT / relative] = render(facts).rstrip("\n") + "\n"
    for path in documentation_files():
        if path in desired:
            continue
        desired[path] = path.read_text(encoding="utf-8")
    for relative, name, render in REGIONS:
        path = REPO_ROOT / relative
        if path not in desired:
            if not path.is_file():
                problems.append(f"{relative}: the page does not exist")
                continue
            desired[path] = path.read_text(encoding="utf-8")
        replaced = replace_region(desired[path], name, render(facts))
        if replaced is None:
            problems.append(f"{relative}: no <!-- gen:{name} --> region")
            continue
        desired[path] = replaced
    for path, text in list(desired.items()):
        new_text, unknown = replace_counts(text, facts.counts)
        desired[path] = new_text
        for name in sorted(set(unknown)):
            problems.append(f"{path.relative_to(REPO_ROOT)}: unknown count '{name}'")
    if problems:
        raise SystemExit("error: " + "; ".join(problems))
    return desired


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="rewrite the generated content")
    mode.add_argument("--check", action="store_true", help="exit 1 when a page differs")
    args = parser.parse_args(argv)

    facts = collect()
    if not args.write and not args.check:
        print(json.dumps(facts.counts, indent=2, sort_keys=True))
        return 0
    if _benchmark_cached() is None:
        print(
            "note: pytest is not installed, so the benchmark region is not checked", file=sys.stderr
        )
    desired = compute(facts)
    differing = [
        p for p, text in desired.items() if not p.is_file() or p.read_text(encoding="utf-8") != text
    ]
    if args.write:
        for path in differing:
            path.write_text(desired[path], encoding="utf-8")
            print(f"wrote {path.relative_to(REPO_ROOT)}")
        if not differing:
            print("nothing to write: every page is current")
        return 0
    if differing:
        for path in differing:
            print(f"out of date: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        print("run: python scripts/gen_docs_counts.py --write", file=sys.stderr)
        return 1
    print(f"ok: {len(desired)} pages match the code")
    return 0


def load_module(path: Path | None = None) -> Any:
    """Import this script as a module (for tests/test_docs.py)."""
    target = path or Path(__file__)
    spec = importlib.util.spec_from_file_location("gen_docs_counts", target)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["gen_docs_counts"] = module
    spec.loader.exec_module(module)
