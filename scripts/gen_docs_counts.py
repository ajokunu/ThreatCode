@dataclass
class Facts:
    rules: tuple[Rule, ...]
    by_provider: dict[str, list[Rule]]
    by_group: dict[str, list[Rule]]
    deprecated: dict[str, list[str]]  # rule file ("aws/s3") -> removed rule ids
    rule_techniques: dict[str, list[str]]  # technique id -> rule ids
    engine_techniques: dict[str, list[str]]  # technique id -> ["attack paths", "boundaries", ...]
    counts: dict[str, Any] = field(default_factory=dict)


def _technique_ids(source: str) -> set[str]:
    return set(re.findall(r"\bT\d{4}(?:\.\d{3})?\b", source))


def _engine_techniques() -> dict[str, list[str]]:
    """Techniques the engine itself assigns, found in the modules that assign them."""
    sources = {
        "attack paths": REPO_ROOT / "src/threatcode/engine/paths.py",
        "boundary crossings": REPO_ROOT / "src/threatcode/engine/boundaries.py",
        "secret findings": REPO_ROOT / "src/threatcode/engine/secrets/iac.py",
    }
    found: dict[str, set[str]] = defaultdict(set)
    for label, path in sources.items():
        for technique in _technique_ids(path.read_text(encoding="utf-8")):
            if technique in mitre.TECHNIQUE_DB and not mitre.is_revoked(technique):
                found[technique].add(label)
    for technique in mitre.PATH_TECHNIQUES.values():
        found[technique].add("attack paths")
    return {t: sorted(labels) for t, labels in sorted(found.items())}


def _rule_techniques(rule: Rule) -> list[str]:
    mitre_meta = rule.metadata.get("mitre") or {}
    return list(mitre_meta.get("techniques") or [])


def provider_of(rule: Rule) -> str:
    return rule.source_group.split("__", 1)[0]


def collect() -> Facts:
    rules = load_builtin_rules()
    by_provider: dict[str, list[Rule]] = defaultdict(list)
    by_group: dict[str, list[Rule]] = defaultdict(list)
    for rule in rules:
        by_provider[provider_of(rule)].append(rule)
        by_group[rule.source_group].append(rule)
    deprecated: dict[str, list[str]] = {}
    for path in sorted(_BUILTIN_DIR.rglob("*.yml")):
        ids = sorted(load_rule_file(path).deprecated_ids)
        if ids:
            deprecated[path.relative_to(_BUILTIN_DIR).with_suffix("").as_posix()] = ids
    rule_techniques: dict[str, list[str]] = defaultdict(list)
    for rule in rules:
        for technique in _rule_techniques(rule):
            rule_techniques[technique].append(rule.id)
    engine = _engine_techniques()
    facts = Facts(
        rules=rules,
        by_provider=dict(by_provider),
        by_group=dict(by_group),
        deprecated=deprecated,
        rule_techniques={t: sorted(ids) for t, ids in sorted(rule_techniques.items())},
        engine_techniques=engine,
    )
    facts.counts = _counts(facts)
    return facts


def _counts(facts: Facts) -> dict[str, Any]:
    all_techniques = set(facts.rule_techniques) | set(facts.engine_techniques)
    rule_tactics = set(mitre.tactics_for_techniques(list(facts.rule_techniques)))
    all_tactics = set(mitre.tactics_for_techniques(sorted(all_techniques)))
    formats = [name for name in FORMATTERS if name != "matrix"]
    counts: dict[str, Any] = {
        "rules": len(facts.rules),
        "rule_files": len(facts.by_group),
        "deprecated_rules": sum(len(v) for v in facts.deprecated.values()),
        "secret_detectors": len(get_secret_rules()),
        "techniques_in_rules": len(facts.rule_techniques),
        "tactics_in_rules": len(rule_tactics),
        "techniques": len(all_techniques),
        "tactics": len(all_tactics),
        "attack_version": mitre.ATTACK_VERSION,
        "attack_techniques": len(mitre.TECHNIQUE_DB),
        "attack_tactics": len(mitre.TACTIC_DB),
        "formats": len(formats),
        "parsers": len(PARSER_REGISTRY),
        "commands": len(_cli().commands),
    }
    for provider in PROVIDERS:
        counts[f"rules_{provider}"] = len(facts.by_provider.get(provider, []))
    for severity in SEVERITY_ORDER:
        counts[f"rules_{severity}"] = sum(1 for r in facts.rules if r.severity == severity)
    for confidence in ("definitive", "heuristic", "absence"):
        counts[f"rules_{confidence}"] = sum(1 for r in facts.rules if r.confidence == confidence)
    cfn = _cfn_module()
    by_cfn = _cfn_rules(cfn, facts)
    counts["cfn_types"] = len(cfn.CFN_TO_TERRAFORM)
    counts["cfn_types_with_rules"] = sum(1 for cfn_type in cfn.CFN_TO_TERRAFORM if by_cfn[cfn_type])
    counts.update(_benchmark_counts())
    return counts


# ---------------------------------------------------------------------------------------
# CloudFormation type coverage (shares its data with scripts/gen_cfn_type_coverage.py)
# ---------------------------------------------------------------------------------------


def _cfn_module() -> Any:
    from threatcode.parsers import _cfn_types

    return _cfn_types


def _cfn_rules(cfn: Any, facts: Facts) -> dict[str, list[str]]:
    """CloudFormation type -> ids of the built-in rules that fire on its Terraform type."""
    by_terraform: dict[str, list[str]] = defaultdict(list)
    for rule in facts.rules:
        for resource_type in rule.resource_types:
            by_terraform[resource_type].append(rule.id)
    return {
        cfn_type: sorted(set(by_terraform.get(terraform_type, [])))
        for cfn_type, terraform_type in cfn.CFN_TO_TERRAFORM.items()
    }


# ---------------------------------------------------------------------------------------
# The planted-issue benchmark (tests/test_quality)
