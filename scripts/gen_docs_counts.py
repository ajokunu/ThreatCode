def _benchmark() -> Any | None:
    """The scored benchmark, or ``None`` when the dev extra (pytest) is not installed."""
    try:
        from tests.test_quality import harness
    except ImportError:
        return None
    results = [harness.run_fixture(e) for e in harness.load_all_expected()]
    return harness, results


_BENCH_CACHE: list[Any] = []


def _benchmark_cached() -> Any | None:
    if not _BENCH_CACHE:
        _BENCH_CACHE.append(_benchmark())
    return _BENCH_CACHE[0]


def _benchmark_counts() -> dict[str, Any]:
    bench = _benchmark_cached()
    if bench is None:
        return {}
    harness, results = bench
    total = harness.totals(results)
    return {
        "benchmark_found": total.found,
        "benchmark_total": total.total,
        "benchmark_recall_percent": round(100 * total.recall),
        "benchmark_violations": total.violations,
        "benchmark_fixtures": len(results),
    }


