#!/usr/bin/env python3
"""Generate the facts the documentation states, and check that the documentation says them.

A documentation page that quotes a rule count, a table of formats or a benchmark result goes stale
the day the code changes.
This script computes those facts from the code and writes them into the pages, and
``tests/test_docs.py`` runs it in ``--check`` mode, so a page cannot drift from the build.

Usage:
    python scripts/gen_docs_counts.py            # print the computed facts as JSON
    python scripts/gen_docs_counts.py --write    # rewrite every generated page and region
    python scripts/gen_docs_counts.py --check    # exit 1 when a page differs from the code

What is generated:

* ``docs/rules.md`` is generated whole: every built-in rule and every removed rule id.
* A region between ``<!-- gen:NAME -->`` and ``<!-- /gen:NAME -->`` in a hand-written page is
  replaced by a table or block computed from the code.
  The regions are listed in ``REGIONS`` below.
* A number followed directly by ``<!-- count:NAME -->`` is a count: ``256<!-- count:rules -->``
  must equal the computed value ``rules``.
  The marker is an HTML comment, so it is invisible on GitHub, on PyPI and in the built site.

The benchmark region runs the planted-issue harness of ``tests/test_quality``, which needs a source
checkout with the dev extra installed.
Without it ``--check`` skips that region and says so.

Exit codes: 0 success, 1 ``--check`` found a difference, 2 usage or import error.
"""

