def _run_snippet(snippet: str) -> str:
    import contextlib
    import io

    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        exec(compile(snippet, "<snippet>", "exec"), {"__name__": "__snippet__"})  # noqa: S102
    return buffer.getvalue().rstrip("\n")


def render_redaction(facts: Facts) -> str:
    output = _run_snippet(REDACTION_SNIPPET)
    return (
        "<!-- runnable -->\n\n```python\n"
        + REDACTION_SNIPPET.rstrip("\n")
        + "\n```\n\nThat prints:\n\n```json\n"
        + output
        + "\n```\n"
    )


def _api_summary(obj: Any) -> str:
    doc = inspect.getdoc(obj) or ""
    first = doc.split("\n\n", 1)[0].replace("\n", " ").strip()
    return first


def render_public_api(facts: Facts) -> str:
    rows = []
    for name in threatcode.__all__:
        obj = getattr(threatcode, name)
        if name == "__version__":
            kind, summary = "str", "The installed version."
        elif inspect.isclass(obj):
            kind = "exception" if issubclass(obj, BaseException) else "class"
            summary = _api_summary(obj)
        else:
            kind, summary = "function", _api_summary(obj)
        rows.append([code(name), kind, summary])
    return table(["Name", "Kind", "What it is"], rows)


